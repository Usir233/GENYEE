func TestValidateDestinationProtectsExistingFiles(t *testing.T) {
	for _, name := range []string{
		"crate itself",
		"outside crate",
		"licenses symlink",
		"output symlink",
		"output file",
		"non-generated directory",
		"invalid manifest",
		"symlink manifest",
	} {
		t.Run(name, func(t *testing.T) {
			crate, outside := t.TempDir(), t.TempDir()
			destination := filepath.Join(crate, "licenses", "rust")
			sentinel := writeFixture(t, outside, "keep.txt", []byte("keep user files\n"))
			switch name {
			case "crate itself":
				destination = crate
			case "outside crate":
				destination = outside
			case "licenses symlink":
				if err := os.Symlink(outside, filepath.Join(crate, "licenses")); err != nil {
					t.Fatal(err)
				}
			case "output symlink":
				if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(outside, destination); err != nil {
					t.Fatal(err)
				}
			case "output file":
				writeFixture(t, crate, "licenses/rust", []byte("ordinary file\n"))
			case "non-generated directory":
				writeFixture(t, destination, "user.txt", []byte("not generated\n"))
			case "invalid manifest":
				writeFixture(t, destination, "rust-dependencies.json", []byte(`{"schemaVersion":1}`))
			case "symlink manifest":
				const markerJSON = `{"schemaVersion":1,"target":"aarch64-apple-darwin","packages":[{"name":"fixture"}]}`
				marker := writeFixture(t, outside, "rust-dependencies.json", []byte(markerJSON))
				if err := os.MkdirAll(destination, 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(marker, filepath.Join(destination, "rust-dependencies.json")); err != nil {
					t.Fatal(err)
				}
			}
			if err := validateDestination(crate, destination); err == nil {
				t.Fatal("unsafe or unowned output destination accepted")
			}
			if data, err := os.ReadFile(sentinel); err != nil || string(data) != "keep user files\n" {
				t.Fatalf("existing unrelated content changed: %q, %v", data, err)
			}
		})
	}
}

func TestValidateDestinationAllowsNewAndPreviouslyGeneratedBundles(t *testing.T) {
	crate := t.TempDir()
	destination := filepath.Join(crate, "licenses", "rust")
	if err := validateDestination(crate, destination); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(destination, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := validateDestination(crate, destination); err != nil {
		t.Fatal(err)
	}
	data, err := json.Marshal(manifest{
		SchemaVersion: 1,
		Target:        "aarch64-apple-darwin",
		Packages:      []packageNotice{{Name: "fixture", Version: "1.0.0"}},
	})
	if err != nil {
		t.Fatal(err)
	}
	writeFixture(t, destination, "rust-dependencies.json", data)
	writeFixture(t, destination, "originals/fixture-1.0.0/LICENSE", []byte("original terms\n"))
	if err := validateDestination(crate, destination); err != nil {
		t.Fatal(err)
	}
}

func TestSupplementalRequiresExactReviewedIdentityAndText(t *testing.T) {
	for _, name := range []string{
		"valid",
		"wrong crate",
		"wrong version",
		"wrong archive checksum",
		"wrong text checksum",
		"empty text",
		"non-UTF8 text",
		"missing text",
		"text symlink",
		"directory symlink",
		"policy symlink",
		"path traversal",
		"bundle path traversal",
	} {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			directory := filepath.Join(root, "licenses", "rust-supplemental")
			text := []byte("Original reviewed license\n")
			pkg := packageNotice{Name: "fixture", Version: "1.2.3", Checksum: strings.Repeat("a", 64)}
			key, checksum := "fixture@1.2.3", pkg.Checksum
			file, path := "materials/LICENSE", "LICENSE-MIT"
			source := "https://example.invalid/fixture/v1.2.3/LICENSE"
			textChecksum := textSHA(text)
			switch name {
			case "wrong crate":
				key = "other@1.2.3"
			case "wrong version":
				key = "fixture@1.2.4"
			case "wrong archive checksum":
				checksum = strings.Repeat("b", 64)
			case "wrong text checksum":
				textChecksum = strings.Repeat("b", 64)
			case "empty text":
				text = nil
				textChecksum = textSHA(text)
			case "non-UTF8 text":
				text = []byte{0xff}
				textChecksum = textSHA(text)
			case "path traversal":
				file = "../external-LICENSE"
			case "bundle path traversal":
				path = "../../external-LICENSE"
			}
			policy := map[string]any{
				key: map[string]any{
					"checksum": checksum,
					"licenses": []map[string]string{{
						"file":   file,
						"path":   path,
						"source": source,
						"sha256": textChecksum,
					}},
				},
			}
			data, err := json.Marshal(policy)
			if err != nil {
				t.Fatal(err)
			}
			writeFixture(t, directory, "sources.json", data)
			if name != "missing text" {
				writeFixture(t, directory, file, text)
			}
			if name == "text symlink" || name == "directory symlink" || name == "policy symlink" {
				outside := t.TempDir()
				var target, link string
				switch name {
				case "text symlink":
					target = writeFixture(t, outside, "LICENSE", text)
					link = filepath.Join(directory, file)
				case "directory symlink":
					writeFixture(t, outside, "LICENSE", text)
					target, link = outside, filepath.Join(directory, "materials")
				case "policy symlink":
					target = writeFixture(t, outside, "sources.json", data)
					link = filepath.Join(directory, "sources.json")
				}
				if err := os.RemoveAll(link); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(target, link); err != nil {
					t.Fatal(err)
				}
			}
			files, err := supplemental(root, pkg)
			if name != "valid" {
				if err == nil {
					t.Fatal("unreviewed or unsafe supplemental original accepted")
				}
				return
			}
			if err != nil || len(files) != 1 {
				t.Fatalf("valid supplemental original: files=%#v err=%v", files, err)
			}
			got := files[0]
			if string(got.data) != string(text) || got.SHA256 != textChecksum || got.Source != source ||
				got.Path != path || got.BundlePath != "originals/fixture-1.2.3/LICENSE-MIT" {
				t.Fatalf("supplemental original/provenance changed: %#v", got)
			}
		})
	}
}

func crateArchive(t *testing.T, path string, kind byte, content []byte) []byte {
	t.Helper()
	var data bytes.Buffer
	gz := gzip.NewWriter(&data)
	archive := tar.NewWriter(gz)
	header := &tar.Header{Name: path, Mode: 0o644, Typeflag: kind}
	switch kind {
	case tar.TypeReg:
		header.Size = int64(len(content))
	case tar.TypeSymlink, tar.TypeLink:
		header.Linkname = "../external-LICENSE"
	}
	if err := archive.WriteHeader(header); err != nil {
		t.Fatal(err)
	}
	if kind == tar.TypeReg {
		if _, err := archive.Write(content); err != nil {
			t.Fatal(err)
		}
	}
	if err := archive.Close(); err != nil {
		t.Fatal(err)
	}
	if err := gz.Close(); err != nil {
		t.Fatal(err)
	}
	return data.Bytes()
}

func TestVerifyRegistryOriginalsRejectsChangedOrAddedCacheText(t *testing.T) {
	original := []byte("Original terms from the locked registry archive\n")
	archive := crateArchive(t, "fixture-1.2.3/LICENSE", tar.TypeReg, original)
	for _, name := range []string{"original", "modified cached license", "added cached license"} {
		t.Run(name, func(t *testing.T) {
			pkg := packageNotice{
				Name:    "fixture",
				Version: "1.2.3",
				Licenses: []fileNotice{
					{Path: "LICENSE", SHA256: textSHA(original)},
					// Reviewed supplemental text is matched by its own policy; it
					// deliberately need not occur in the registry archive.
					{
						Path:   "LICENSE-supplemental",
						Source: "https://example.invalid/LICENSE",
						SHA256: textSHA([]byte("reviewed supplemental")),
					},
				},
			}
			switch name {
			case "modified cached license":
				pkg.Licenses[0].SHA256 = textSHA([]byte("Local edits disguised as original terms\n"))
			case "added cached license":
				pkg.Licenses = append(pkg.Licenses, fileNotice{Path: "NEW-LICENSE", SHA256: textSHA(original)})
			}
			err := verifyRegistryOriginals(archive, pkg)
			if name == "original" && err != nil {
				t.Fatal(err)
			}
			if name != "original" && err == nil {
				t.Fatal("mutable cache text accepted without a matching locked original")
			}
		})
	}
}

func TestVerifyRegistryOriginalsRejectsMissingOrNonregularOriginals(t *testing.T) {
	original := []byte("Original license\n")
	pkg := packageNotice{
		Name:     "fixture",
		Version:  "1.2.3",
		Licenses: []fileNotice{{Path: "LICENSE", SHA256: textSHA(original)}},
	}
	for _, tc := range []struct {
		name, path string
		kind       byte
	}{
		{"missing", "fixture-1.2.3/README", tar.TypeReg},
		{"symlink", "fixture-1.2.3/LICENSE", tar.TypeSymlink},
		{"hardlink", "fixture-1.2.3/LICENSE", tar.TypeLink},
		{"directory", "fixture-1.2.3/LICENSE", tar.TypeDir},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if err := verifyRegistryOriginals(crateArchive(t, tc.path, tc.kind, original), pkg); err == nil {
				t.Fatal("unusable archive original accepted")
			}
		})
	}
}
