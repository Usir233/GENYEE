func writeFixture(t *testing.T, root, name string, data []byte) string {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func textSHA(data []byte) string {
	h := sha256.Sum256(data)
	return hex.EncodeToString(h[:])
}

func lockedPackage(name, version, source, checksum string) string {
	return fmt.Sprintf(
		"[[package]]\nname = %q\nversion = %q\nsource = %q\nchecksum = %q\n",
		name, version, source, checksum,
	)
}

func TestLockChecksumsPreservesExactRegistryIdentities(t *testing.T) {
	const registry = "registry+https://github.com/rust-lang/crates.io-index"
	first, second := strings.Repeat("a", 64), strings.Repeat("b", 64)
	lock := "# Automatically generated by Cargo.\nversion = 4\n\n" +
		"[[package]]\nname = \"local-root\"\nversion = \"0.1.0\"\n\n" +
		lockedPackage("shared-name", "1.0.0", registry, first) + "dependencies = [\n \"other 2.0.0\",\n]\n\n" +
		lockedPackage("shared-name", "2.0.0", registry, second)
	got, err := lockChecksums([]byte(lock))
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]string{
		"shared-name@1.0.0@" + registry: first,
		"shared-name@2.0.0@" + registry: second,
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("checksums = %#v, want %#v", got, want)
	}
}

func TestLockChecksumsRejectsAmbiguousOrInvalidPackages(t *testing.T) {
	const registry = "registry+https://github.com/rust-lang/crates.io-index"
	checksum := strings.Repeat("a", 64)
	valid := lockedPackage("crate", "1.0.0", registry, checksum)
	tests := map[string]string{
		"duplicate identity":    valid + valid,
		"conflicting duplicate": valid + lockedPackage("crate", "1.0.0", registry, strings.Repeat("b", 64)),
		"nonhex checksum":       lockedPackage("crate", "1.0.0", registry, strings.Repeat("z", 64)),
		"short checksum":        lockedPackage("crate", "1.0.0", registry, "abcd"),
		"missing name":          lockedPackage("", "1.0.0", registry, checksum),
		"missing version":       lockedPackage("crate", "", registry, checksum),
		"missing source":        lockedPackage("crate", "1.0.0", "", checksum),
		"unquoted checksum":     strings.Replace(valid, fmt.Sprintf("%q", checksum), checksum, 1),
	}
	for name, lock := range tests {
		t.Run(name, func(t *testing.T) {
			if _, err := lockChecksums([]byte(lock)); err == nil {
				t.Fatal("malformed lockfile accepted")
			}
		})
	}
}

func TestCollectPreservesNonstandardThirdPartyNotices(t *testing.T) {
	root := t.TempDir()
	originals := map[string]string{
		"LICENSE-MIT":                 "Original MIT text\n",
		"THIRD_PARTY_LICENSES":        "Third-party original licenses\n",
		"docs/THIRD-PARTY-NOTICES.md": "Original third-party notices\n",
		"licenses/vendor/terms.txt":   "Vendored terms with UTF-8: 著作权\n",
		"LEGAL-TERMS.txt":             "Explicitly declared terms\n",
	}
	for path, data := range originals {
		writeFixture(t, root, path, []byte(data))
	}
	for _, path := range []string{
		"README.md",
		"src/license.rs",
		"target/LICENSE",
		".git/LICENSE",
		"licenses/rust/originals/old/LICENSE",
		"patched-anydoc/LICENSE",
	} {
		writeFixture(t, root, path, []byte("must not be re-collected\n"))
	}
	files, err := collect(root, filepath.Join(root, "LEGAL-TERMS.txt"), "originals/fixture-1.0.0", false)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != len(originals) {
		t.Fatalf("collected %d files, want %d: %#v", len(files), len(originals), files)
	}
	for _, file := range files {
		text, found := originals[file.Path]
		if !found || string(file.data) != text || file.SHA256 != textSHA([]byte(text)) ||
			file.BundlePath != "originals/fixture-1.0.0/"+file.Path {
			t.Errorf("original content/provenance not preserved: %#v", file)
		}
	}
}

func TestCollectFailsClosedOnUnusableLicenseText(t *testing.T) {
	for _, name := range []string{
		"missing",
		"empty",
		"non-UTF8",
		"symlink",
		"symlink directory",
		"missing declared file",
	} {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			explicit := ""
			switch name {
			case "empty":
				writeFixture(t, root, "LICENSE", nil)
			case "non-UTF8":
				writeFixture(t, root, "LICENSE", []byte{0xff})
			case "symlink":
				target := writeFixture(t, t.TempDir(), "external-license", []byte("external text\n"))
				if err := os.Symlink(target, filepath.Join(root, "LICENSE")); err != nil {
					t.Fatal(err)
				}
			case "symlink directory":
				target := t.TempDir()
				writeFixture(t, target, "LICENSE", []byte("external text\n"))
				if err := os.Symlink(target, filepath.Join(root, "licenses")); err != nil {
					t.Fatal(err)
				}
			case "missing declared file":
				writeFixture(t, root, "LICENSE", []byte("Some other valid license\n"))
				explicit = filepath.Join(root, "declared-but-missing.txt")
			}
			_, err := collect(root, explicit, "originals/fixture-1.0.0", false)
			if err == nil {
				t.Fatal("unusable original license accepted")
			}
			if name == "missing" && !errors.Is(err, errMissingLicense) {
				t.Fatalf("missing original must allow reviewed fallback: %v", err)
			}
			if name != "missing" && errors.Is(err, errMissingLicense) {
				t.Fatalf("invalid or missing declared license must not trigger fallback: %v", err)
			}
		})
	}
}

